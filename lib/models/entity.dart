/// Общее для всех записей каталога: числовой идентификатор и пометка логического удаления.
/// Нужен обобщённым классам — репозиторию в памяти, состоянию списка и таблице `EntityTable`: им достаточно знать, как достать идентификатор и
/// удалена ли запись, а всё остальное про товар или производителя им знать не нужно.
abstract interface class Entity {
  int get id;

  /// Момент логического удаления. `null` — запись активна.
  DateTime? get deletedAt;

  bool get isDeleted;
}
